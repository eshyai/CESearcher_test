ALIAS_TO_CANONICAL: dict[str, str] = {
    alias.lower(): canonical
    for canonical, aliases in SYNONYM_GROUPS.items()
    for alias in aliases
}

# 所有别名按长度倒序（最长匹配优先）
SORTED_ALIASES: tuple[str, ...] = tuple(
    sorted(ALIAS_TO_CANONICAL, key=len, reverse=True)
)


def canonical_of(term: str) -> str:
    """把任意写法归一为规范名；不在词表内则原样返回（小写）。"""
    key = (term or "").strip().lower()
    return ALIAS_TO_CANONICAL.get(key, key)


def aliases_of(canonical: str) -> tuple[str, ...]:
    """返回规范名对应的全部写法（含自身）；词表外返回单元素元组。"""
    return SYNONYM_GROUPS.get(canonical, (canonical,))


def is_generic(term: str) -> bool:
    """判断一个词是否为「单独不足以判定命中」的泛词。"""
    return canonical_of(term) in GENERIC_TERMS
